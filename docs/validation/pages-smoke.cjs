const {chromium}=require('playwright');
(async()=>{
 const b=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 const p=await b.newPage({viewport:{width:1440,height:1000}});let apiCalls=[];let errors=[];
 p.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))apiCalls.push(r.url())});p.on('pageerror',e=>errors.push(e.message));
 await p.goto('http://127.0.0.1:8766/cubaloop/');
 await p.getByText('Demostración interactiva',{exact:true}).waitFor();
 await p.getByRole('button',{name:'Configuración'}).click();
 await p.getByRole('heading',{name:'999 AED / 30 días'}).waitFor();
 await p.getByRole('heading',{name:'1499 AED / 30 días'}).waitFor();
 if(await p.getByRole('button',{name:'Elegir Pro'}).isEnabled())throw Error('Demo permits checkout');
 await p.screenshot({path:'/tmp/jota-plans.png',fullPage:true});
 await p.getByRole('button',{name:'Clientes',exact:true}).click();
 await p.getByRole('button',{name:'Iniciar proyecto'}).click();
 await p.getByRole('button',{name:'Usar plantilla local'}).click();
 await p.getByLabel('Enlace al prototipo').fill('https://example.com/demo');
 await p.getByRole('button',{name:'Guardar para revisión'}).click();
 await p.getByLabel('He revisado el prototipo y la propuesta guardada.').check();
 await p.getByRole('button',{name:'Aprobar propuesta'}).click();
 await p.getByLabel('Ya he contactado al cliente por mi cuenta.').check();
 await p.getByRole('button',{name:'Registrar contacto'}).click();
 await p.getByRole('heading',{name:'Tu próximo proyecto'}).waitFor();
 await p.getByRole('link',{name:'jota'}).click();
 await p.getByRole('heading',{name:/Tu próximo gran cliente/}).waitFor();
 if(!p.url().endsWith('/cubaloop/'))throw Error('Base path broken');
 await p.setViewportSize({width:390,height:844});
 if(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Overflow');
 if(errors.length||apiCalls.length)throw Error(JSON.stringify({errors,apiCalls}));
 console.log('PASS: Pages subpath, final pricing, full demo flow, disabled payments, no API calls, mobile layout');
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
