const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765');
 await page.getByRole('button',{name:'Prueba Jota gratis'}).click();
 await page.getByLabel('Tu correo').fill(`smoke${Date.now()}@example.test`);
 await page.getByLabel('Contraseña').fill('Smoke-test-password-123');
 await page.getByRole('button',{name:'Crear mi espacio'}).click();
 await page.getByRole('heading',{name:/Tu próximo gran cliente/}).waitFor();
 await page.screenshot({path:'/tmp/jota-dashboard.png',fullPage:true});
 await page.getByRole('button',{name:'Añadir cliente'}).click();
 await page.getByLabel('Nombre del negocio').fill('Studio Oliva');
 await page.getByLabel('Sector',{exact:true}).fill('Architecture');
 await page.getByLabel('Correo de contacto').fill('hello@example.test');
 await page.getByRole('button',{name:'Guardar cliente'}).click();
 await page.getByRole('button',{name:'Iniciar proyecto'}).click();
 await page.getByRole('button',{name:'Usar plantilla local'}).click();
 await page.getByLabel('Enlace al prototipo').fill('https://example.com/demo');
 await page.getByRole('button',{name:'Guardar para revisión'}).click();
 await page.getByLabel('He revisado el prototipo y la propuesta guardada.').check();
 await page.getByRole('button',{name:'Aprobar propuesta'}).click();
 await page.getByLabel('Ya he contactado al cliente por mi cuenta.').check();
 await page.getByRole('button',{name:'Registrar contacto'}).click();
 await page.getByRole('heading',{name:'Tu próximo proyecto'}).waitFor();
 await page.getByRole('button',{name:'Vista general'}).click();
 await page.screenshot({path:'/tmp/jota-dashboard-complete.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/jota-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(errors.length||overflow)throw new Error(JSON.stringify({errors,overflow}));
 console.log('PASS: register → lead → proposal → review → approval → manual contact; desktop/mobile; no page errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
